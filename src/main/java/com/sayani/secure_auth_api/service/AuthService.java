package com.sayani.secure_auth_api.service;

import com.sayani.secure_auth_api.dto.AuthResponse;
import com.sayani.secure_auth_api.dto.ForgotPasswordRequest;
import com.sayani.secure_auth_api.dto.LoginRequest;
import com.sayani.secure_auth_api.dto.RegisterRequest;
import com.sayani.secure_auth_api.dto.ResetPasswordRequest;
import com.sayani.secure_auth_api.dto.VerifyOtpRequest;
import com.sayani.secure_auth_api.entity.Role;
import com.sayani.secure_auth_api.entity.User;
import com.sayani.secure_auth_api.repository.UserRepository;
import com.sayani.secure_auth_api.security.JwtService;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.security.authentication.AuthenticationManager;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.core.Authentication;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.stereotype.Service;

import java.security.SecureRandom;
import java.time.LocalDateTime;
import java.util.Map;

@Slf4j
@Service
@RequiredArgsConstructor
public class AuthService {

    private final UserRepository userRepository;
    private final PasswordEncoder passwordEncoder;
    private final JwtService jwtService;
    private final AuthenticationManager authenticationManager;
    private final EmailService emailService;

    private static final SecureRandom SECURE_RANDOM = new SecureRandom();

    /**
     * Registers a new user. If password is not provided, automatically generates
     * a secure password following the pattern: <FirstName>@<auto-generated number>.
     * Dispatches welcome credentials email.
     */
    public AuthResponse register(RegisterRequest request) {
        String email = request.getEmail();
        if (email == null || email.isBlank()) {
            throw new IllegalArgumentException("Username or email is required");
        }

        if (userRepository.existsByEmail(email)) {
            throw new IllegalArgumentException("User is already registered: " + email);
        }

        String rawPassword = request.getPassword();
        if (rawPassword == null || rawPassword.trim().isEmpty()) {
            rawPassword = generateAutoPassword(request.getName());
        }

        var user = User.builder()
                .name(request.getName())
                .email(email)
                .password(passwordEncoder.encode(rawPassword))
                .role(Role.ROLE_USER)
                .twoFactorEnabled(true)
                .build();

        userRepository.save(user);

        // Send registration email with username and auto-generated password
        emailService.sendRegistrationEmail(user.getEmail(), user.getName(), rawPassword);

        return AuthResponse.builder()
                .status("REGISTERED")
                .name(user.getName())
                .email(user.getEmail())
                .role(user.getRole().name())
                .message("User registered successfully. Login credentials sent to your registered email.")
                .build();
    }

    /**
     * Authenticates login credentials. If login occurs from an unrecognized device,
     * triggers Two-Factor Authentication and sends an OTP email.
     */
    public AuthResponse login(LoginRequest request) {
        String loginIdentifier = request.getUsername();
        if (loginIdentifier == null || loginIdentifier.isBlank()) {
            throw new IllegalArgumentException("Username or email is required");
        }

        // 1. Authenticate user credentials (username/email and password)
        Authentication authentication = authenticationManager.authenticate(
                new UsernamePasswordAuthenticationToken(
                        loginIdentifier,
                        request.getPassword()
                )
        );

        SecurityContextHolder.getContext().setAuthentication(authentication);

        var user = userRepository.findByEmail(loginIdentifier)
                .orElseThrow(() -> new IllegalArgumentException("Invalid username or password"));

        String requestedDevice = request.getDeviceId();
        boolean isRecognizedDevice = user.getLastKnownDeviceId() != null && user.getLastKnownDeviceId().equals(requestedDevice);

        // 2. Unrecognized device or first login -> Trigger Two-Factor Authentication (OTP)
        if (!isRecognizedDevice && user.isTwoFactorEnabled()) {
            String otp = String.format("%06d", SECURE_RANDOM.nextInt(1_000_000));
            user.setCurrentOtp(otp);
            user.setOtpExpiryTime(LocalDateTime.now().plusMinutes(5));
            userRepository.save(user);

            // Send OTP alert email to the registered user
            emailService.sendOtpEmail(user.getEmail(), user.getName(), otp, requestedDevice);

            return AuthResponse.builder()
                    .status("OTP_REQUIRED")
                    .email(user.getEmail())
                    .name(user.getName())
                    .twoFactorRequired(true)
                    .deviceId(requestedDevice)
                    .message("Unrecognized device detected. A 6-digit OTP has been sent to your registered email.")
                    .build();
        }

        // 3. Recognized / trusted device -> Directly issue JWT
        var jwtToken = jwtService.generateTokenFromCredentials(
                user.getUsername(),
                request.getPassword(),
                Map.of("role", user.getRole().name())
        );

        return AuthResponse.builder()
                .status("SUCCESS")
                .token(jwtToken)
                .tokenType("Bearer")
                .name(user.getName())
                .email(user.getEmail())
                .role(user.getRole().name())
                .deviceId(requestedDevice)
                .twoFactorRequired(false)
                .message("Authentication successful (Recognized Device)")
                .build();
    }

    /**
     * Verifies 2FA OTP for new/unrecognized device login and registers device.
     */
    public AuthResponse verifyOtp(VerifyOtpRequest request) {
        String loginIdentifier = request.getUsername();
        if (loginIdentifier == null || loginIdentifier.isBlank()) {
            throw new IllegalArgumentException("Username or email is required");
        }

        var user = userRepository.findByEmail(loginIdentifier)
                .orElseThrow(() -> new IllegalArgumentException("User not found with email: " + loginIdentifier));

        // Validate OTP existence
        if (user.getCurrentOtp() == null || !user.getCurrentOtp().equals(request.getOtp().trim())) {
            throw new IllegalArgumentException("Invalid OTP code provided.");
        }

        // Validate OTP expiry
        if (user.getOtpExpiryTime() == null || user.getOtpExpiryTime().isBefore(LocalDateTime.now())) {
            throw new IllegalArgumentException("OTP code has expired. Please initiate login again.");
        }

        // Mark device as recognized and clear the used OTP
        user.setLastKnownDeviceId(request.getDeviceId());
        user.setCurrentOtp(null);
        user.setOtpExpiryTime(null);
        userRepository.save(user);

        // Issue JWT token upon successful 2FA verification
        var jwtToken = jwtService.generateToken(
                Map.of("role", user.getRole().name()),
                user.getUsername()
        );

        return AuthResponse.builder()
                .status("SUCCESS")
                .token(jwtToken)
                .tokenType("Bearer")
                .name(user.getName())
                .email(user.getEmail())
                .role(user.getRole().name())
                .deviceId(request.getDeviceId())
                .twoFactorRequired(false)
                .message("Two-Factor Authentication verified successfully. Device registered.")
                .build();
    }

    /**
     * Initiates Forgot Password process: Generates a 6-digit Reset OTP and dispatches it via email.
     */
    public AuthResponse forgotPassword(ForgotPasswordRequest request) {
        String email = request.getEmail();
        if (email == null || email.isBlank()) {
            throw new IllegalArgumentException("Registered email or username is required.");
        }

        var user = userRepository.findByEmail(email)
                .orElseThrow(() -> new IllegalArgumentException("No account found registered with email: " + email));

        // Generate 6-digit OTP code for password reset
        String otp = String.format("%06d", SECURE_RANDOM.nextInt(1_000_000));
        user.setCurrentOtp(otp);
        user.setOtpExpiryTime(LocalDateTime.now().plusMinutes(5));
        userRepository.save(user);

        // Dispatch reset OTP email
        emailService.sendPasswordResetOtpEmail(user.getEmail(), user.getName(), otp);

        return AuthResponse.builder()
                .status("OTP_SENT")
                .email(user.getEmail())
                .name(user.getName())
                .message("Password reset OTP has been sent to your registered email.")
                .build();
    }

    /**
     * Validates the Reset OTP and updates the user password, followed by a confirmation email.
     */
    public AuthResponse resetPassword(ResetPasswordRequest request) {
        String email = request.getEmail();
        if (email == null || email.isBlank()) {
            throw new IllegalArgumentException("Registered email or username is required.");
        }

        var user = userRepository.findByEmail(email)
                .orElseThrow(() -> new IllegalArgumentException("No account found registered with email: " + email));

        if (user.getCurrentOtp() == null || !user.getCurrentOtp().equals(request.getOtp().trim())) {
            throw new IllegalArgumentException("Invalid password reset OTP code.");
        }

        if (user.getOtpExpiryTime() == null || user.getOtpExpiryTime().isBefore(LocalDateTime.now())) {
            throw new IllegalArgumentException("Password reset OTP has expired. Please request a new OTP.");
        }

        // Update with encoded new password
        user.setPassword(passwordEncoder.encode(request.getNewPassword()));
        user.setCurrentOtp(null);
        user.setOtpExpiryTime(null);
        userRepository.save(user);

        // Send confirmation notification email
        emailService.sendPasswordChangeSuccessEmail(user.getEmail(), user.getName());

        return AuthResponse.builder()
                .status("SUCCESS")
                .email(user.getEmail())
                .name(user.getName())
                .message("Your password has been changed successfully. You can now log in with your new password.")
                .build();
    }

    /**
     * Helper to generate auto-generated password in format <FirstName>@<5-digit number>
     */
    private String generateAutoPassword(String fullName) {
        String firstName = "User";
        if (fullName != null && !fullName.trim().isEmpty()) {
            String[] parts = fullName.trim().split("\\s+");
            if (parts.length > 0 && !parts[0].isEmpty()) {
                String first = parts[0];
                firstName = first.substring(0, 1).toUpperCase() + (first.length() > 1 ? first.substring(1) : "");
            }
        }
        int randomNum = 10000 + SECURE_RANDOM.nextInt(90000);
        return firstName + "@" + randomNum;
    }
}
